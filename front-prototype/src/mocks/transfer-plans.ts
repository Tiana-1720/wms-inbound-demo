import { sumTransferPlanLines } from '@/domain/transfer-plan/filter'
import type { TransferPlan } from '@/domain/transfer-plan/types'

function withSummary(
  plan: Omit<TransferPlan, '箱数' | '重量' | '体积'> &
    Partial<Pick<TransferPlan, '箱数' | '重量' | '体积'>>,
): TransferPlan {
  const summary = sumTransferPlanLines(plan.明细)
  return {
    ...plan,
    箱数: summary.箱数,
    重量: summary.重量,
    体积: summary.体积,
  }
}

